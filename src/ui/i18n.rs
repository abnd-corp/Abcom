//! Catalogue des libelles de l'interface.
//!
//! Toutes les chaines traduites vivent ici, et nulle part ailleurs : ajouter
//! une langue revient a ajouter une colonne dans ce fichier, au lieu de
//! reprendre chaque appel disperse dans l'UI.

use super::UiLanguage;

/// Un libelle et ses traductions.
pub(crate) struct Entry {
    pub(crate) fr: &'static str,
    pub(crate) en: &'static str,
}

impl Entry {
    /// Libelle dans la langue demandee.
    pub(crate) const fn get(&self, language: UiLanguage) -> &'static str {
        match language {
            UiLanguage::French => self.fr,
            UiLanguage::English => self.en,
        }
    }
}

macro_rules! catalog {
    ($($name:ident => ($fr:literal, $en:literal),)*) => {
        $(pub(crate) const $name: Entry = Entry { fr: $fr, en: $en };)*

        /// Toutes les entrees, pour les controles de coherence.
        #[cfg(test)]
        pub(crate) const ALL: &[(&str, Entry)] = &[$((stringify!($name), $name),)*];
    };
}

